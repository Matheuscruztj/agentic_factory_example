from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

OUTPUT = Path(__file__).parents[1] / "apps/factory-web/src/lib/api/generated.ts"
ROOT = Path(__file__).parents[1]
sys.path[:0] = [
    str(ROOT / "apps/factory-api/src"),
    str(ROOT / "packages/shared-contracts/src"),
    str(ROOT / "packages/task-engine/src"),
]

from factory_api.main import app  # noqa: E402


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        options = schema.get("anyOf", schema.get("oneOf", []))
        return " | ".join(ts_type(option) for option in options)
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        return "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}.get(
        kind, "unknown"
    )


def render() -> str:
    spec = app.openapi()
    digest = hashlib.sha256(
        json.dumps(spec, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()
    lines = [
        "// Generated by scripts/gen_client.py; do not edit.",
        f'export const openApiDigest = "{digest}"',
        "",
    ]
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        props = schema.get("properties")
        if not props:
            continue
        required = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for field, field_schema in props.items():
            optional = "" if field in required else "?"
            lines.append(f"  {field}{optional}: {ts_type(field_schema)}")
        lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print("generated client is stale; run python scripts/gen_client.py")
            return 1
        print('{"task_id":"FAC-029","status":"pass","exit_code":0}')
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print('{"task_id":"FAC-029","status":"generated","exit_code":0}')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
